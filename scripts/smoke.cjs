/** Actual browser integration: needs Playwright and Chromium installed externally. */
const assert = require('node:assert/strict');
const {mkdtemp,readFile} = require('node:fs/promises');
const {tmpdir} = require('node:os');
const {join} = require('node:path');
(async () => {
  const {chromium} = require('playwright');
  const {createLocalServer} = await import('./serve.js');
  const server = createLocalServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({headless: true, ...(process.env.LAKE_CHROMIUM ? {executablePath: process.env.LAKE_CHROMIUM} : {}), args: ['--no-sandbox']});
    const page = await browser.newPage({viewport: {width: 1440, height: 1050}});
    const origin = `http://127.0.0.1:${server.address().port}`;
    const screenshotDir = process.env.LAKE_SCREENSHOT_DIR || await mkdtemp(join(tmpdir(), 'lake-ui-'));
    const errors = [], external = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('dialog', dialog => dialog.accept());
    page.on('request', request => { if (!request.url().startsWith(origin) && !request.url().startsWith('blob:')) external.push(request.url()); });
    await page.goto(origin);
    await page.getByRole('heading', {name: /Talent opens up possibilities/}).waitFor();
    await page.screenshot({path: join(screenshotDir, 'lake-management-desktop.png'), fullPage: true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,'Management home fits mobile');
    await page.screenshot({path:join(screenshotDir,'lake-management-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1050});
    await page.locator('#primary-navigation [data-view=dashboard]').click();
    await page.getByRole('heading', {name: 'Investment pipeline'}).waitFor();
    await page.locator('[data-action=new]').first().click();
    await page.locator('[name=label]').fill('Example A — assumption');
    await page.locator('[name=capital]').fill('100000');
    await page.locator('[name=upfrontFee]').fill('5000');
    assert.equal(await page.locator('#save-opportunity').isDisabled(), true);
    assert.equal(await page.locator('[name=diligence-revenue]').isChecked(), false);
    await page.getByRole('button', {name: 'Recalculate analysis', exact: true}).click();
    await page.locator('#save-opportunity').click();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('lake-investor-v2')).opportunities[0].diligence.revenue), false);
    await page.locator('#primary-navigation [data-view=opportunities]').click();
    await page.locator('[data-clone]').click();
    await page.locator('[name=label]').fill('Example B — assumption');
    await page.locator('[name=revenue]').fill('100000');
    await page.getByRole('button', {name: 'Recalculate analysis', exact: true}).click();
    await page.locator('#save-opportunity').click();
    await page.locator('#primary-navigation [data-view=compare]').click();
    await page.getByRole('heading', {name: '2 independent cases selected'}).waitFor();
    await page.locator('#common-rate-enabled').check();
    await page.locator('#common-rate').fill('20');
    await page.getByRole('button', {name: 'Apply to comparison'}).click();
    const csvDownload = page.waitForEvent('download');
    await page.locator('#export-comparison').click();
    assert.equal((await csvDownload).suggestedFilename(), 'lake-comparison.csv');
    await page.locator('#primary-navigation [data-view=opportunities]').click();
    await page.locator('[data-allocate]').first().click();
    assert.equal(await page.locator('[data-remove]').count(), 1);
    await page.reload();
    await page.locator('#primary-navigation [data-view=portfolio]').click();
    assert.equal(await page.locator('[data-remove]').count(), 1);
    const exported = await page.evaluate(() => localStorage.getItem('lake-investor-v2'));
    const parsed = JSON.parse(exported); assert.equal(parsed.positions[0].model.upfrontFee, 5000);
    await page.locator('#budget').fill('105000');
    await page.getByRole('button', {name: 'Update', exact: true}).click();
    await page.locator('#primary-navigation [data-view=opportunities]').click();
    await page.locator('[data-allocate]').first().click();
    assert.match(await page.locator('#status').textContent(), /Insufficient/);
    await page.locator('#primary-navigation [data-view=portfolio]').click();
    await page.locator('#import-portfolio').setInputFiles({name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{broken')});
    await page.waitForFunction(() => document.getElementById('status').textContent.includes('Import rejected'));
    await page.locator('#import-portfolio').setInputFiles({name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(exported)});
    await page.waitForFunction(() => document.getElementById('status').textContent.includes('Saved'));
    await page.locator('#primary-navigation [data-view=sources]').click();
    assert.match(await page.locator('#content').textContent(), /SHA-256 OK/);
    await page.locator('#primary-navigation [data-view=model]').click();
    await page.locator('#dated-tool summary').click();
    await page.locator('#dated-input').fill('2026-01-01 ; -100\n2027-01-01 ; 110');
    await page.getByRole('button', {name: 'Calculate dated cash flows'}).click();
    assert.match(await page.locator('#dated-results').textContent(), /10.0/);
    await page.locator('#primary-navigation [data-view=dashboard]').click();
    await page.screenshot({path: join(screenshotDir, 'desktop.png'), fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    for (const view of ['dashboard', 'opportunities', 'model', 'compare', 'portfolio', 'sources']) {
      await page.locator(`#primary-navigation [data-view=${view}]`).click();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `No page overflow in ${view}`);
    }
    await page.screenshot({path: join(screenshotDir, 'mobile.png'), fullPage: true});
    await page.locator('#primary-navigation [data-view=dashboard]').click();
    const originalWorkspace = await page.evaluate(() => localStorage.getItem('lake-investor-v2'));
    await page.locator('[data-action=start-demo]').click();
    await page.getByText('FICTIONAL DEMONSTRATION · NO REAL INVESTMENT', {exact:true}).waitFor();
    await page.locator('[data-action=demo-create]').first().click();
    await page.getByRole('button', {name:'Recalculate analysis',exact:true}).click();
    await page.locator('#save-opportunity').click();
    await page.locator('#primary-navigation [data-view=compare]').click();
    assert.equal(await page.locator('.negative-fill').count(),1);
    assert.equal(await page.locator('.positive-fill').count(),1);
    await page.locator('[data-allocate]').first().click();
    await page.locator('#primary-navigation [data-view=compare]').click();
    await page.locator('[data-allocate="demo-case-b"]').click();
    const htmlDownload = page.waitForEvent('download');
    await page.locator('#export-report').click();
    const reportPath = await (await htmlDownload).path();
    const reportHtml = await readFile(reportPath,'utf8');
    assert.match(reportHtml,/FICTIONAL DEMONSTRATION/);
    assert.doesNotMatch(reportHtml,/<script/);
    assert.equal(await page.evaluate(() => localStorage.getItem('lake-investor-v2')),originalWorkspace);
    await page.locator('[data-action=exit-demo]').click();
    assert.equal(await page.evaluate(() => localStorage.getItem('lake-investor-v2')),originalWorkspace);
    assert.deepEqual(errors, []); assert.deepEqual(external, []);
    console.log('PASS Chromium: create/clone, recalculate, compare, common discount, CSV, allocation, persistence, budget, import, audit, dated IRR, all mobile views, no external requests/page errors.');
    console.log('Screenshots:', screenshotDir);
  } finally {
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });

